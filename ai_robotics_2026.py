import numpy as np
import pandas as pd

# System Parameters (Sourced from Document)
T = 1.2 # Trajectory duration (s)
dt = 0.005 # 5 ms control cycle
time_steps = np.arange(0, T + dt, dt)
delays = [0, 0.020, 0.050] # 0, 20, 50 ms

# Joint 2 (Shoulder) parameters
q0 = np.deg2rad(25.0)
qf = np.deg2rad(40.0)

Kp = 900.0 # PD Gain (N.m/rad)
Kd = 60.0  # PD Gain (N.m.s/rad)
tau_max = 75.0 # Torque limit for J2 (N.m)
M_22 = 2.264 # Mass matrix diagonal for J2 (kg.m^2)

# Gravity approximation derived from static check (50 N.m at 60 deg)
mgL = 50.0 / np.cos(np.deg2rad(60))

data = []

for delay in delays:
    for t in time_steps:
        # 1. Quintic Trajectory Equations
        s = t / T
        if s <= 1.0:
            q_ref = q0 + (qf - q0) * (10*s**3 - 15*s**4 + 6*s**5)
            qdot_ref = ((qf - q0) / T) * (30*s**2 - 60*s**3 + 30*s**4)
            qddot_ref = ((qf - q0) / T**2) * (60*s - 180*s**2 + 120*s**3)
        else:
            q_ref, qdot_ref, qddot_ref = qf, 0, 0

        # 2. Tracking Error with Delay Injection Equation
        # e_m(t) ≈ e_q(t) + Δ * qdot(t)
        base_oscillation = np.sin(10 * np.pi * t) * (delay * 5)
        e_q = base_oscillation * qdot_ref

        e_m = e_q + (delay * qdot_ref)

        # 3. Torque Equation (PD + Gravity + Delay negative damping)
        tau_pd = Kp * e_q + Kd * (e_q / dt if dt > 0 else 0) * 0.1
        tau_delay_injection = Kp * delay * qdot_ref + Kd * delay * qddot_ref
        G_q = -mgL * np.cos(q_ref) # Gravity vector

        tau_cmd = tau_pd + tau_delay_injection - G_q

        # 4. Torque Saturation Equation
        tau_actual = np.clip(tau_cmd, -tau_max, tau_max)

        # 5. Energy Equations
        KE = 0.5 * M_22 * (qdot_ref - e_m)**2
        PE = mgL * np.sin(q_ref)
        Total_E = KE + PE

        data.append({
            "time_s": round(t, 3),
            "delay_ms": int(delay * 1000),
            "q_ref_rad": round(q_ref, 4),
            "qdot_ref_rad_s": round(qdot_ref, 4),
            "tracking_error_rad": round(e_m, 4),
            "tau_cmd_Nm": round(tau_cmd, 2),
            "tau_actual_Nm": round(tau_actual, 2),
            "kinetic_energy_J": round(KE, 2),
            "potential_energy_J": round(PE, 2),
            "total_energy_J": round(Total_E, 2)
        })

df_math = pd.DataFrame(data)
